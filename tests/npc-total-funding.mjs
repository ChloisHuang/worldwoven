// Real regression risks: spending bank money must lower the interest minimum;
// cancellation must restore the original split without changing player rules.
import assert from 'node:assert/strict';
import {createCurrencyLedger} from '../source/game/currency-ledger.js';
let day=0,durable,reject=false;
const options={getClock:()=>({day}),saveState:next=>{if(reject)return false;durable=structuredClone(next);}};
let ledger=createCurrencyLedger(options);
assert(ledger.creditWageToBank({amount:250,receiptId:'earned',currency:'japan',roleId:'cook',slotId:'kitchen',day}).ok);
assert(ledger.withdraw(40,'cash','japan').ok);
day=1;assert(ledger.observeDay().ok);
const before=ledger.balances().japan;
assert.equal(ledger.reserve(50,'player-cash-only','japan').code,'insufficient-cash');
reject=true;assert.equal(ledger.reserveFromTotal(90,'npc-meal','japan').code,'save-failed');assert.deepEqual(ledger.balances().japan,before);
reject=false;assert(ledger.reserveFromTotal(90,'npc-meal','japan').ok);
assert.deepEqual(ledger.reservations()[0].sourceSplit,{cash:40,bank:50});
assert.equal(ledger.state().interest.minimum.japan,160);
assert(ledger.reserveFromTotal(90,'npc-meal','japan').replayed);
assert.equal(ledger.reserve(90,'npc-meal','japan').code,'request-conflict');
assert(ledger.creditWageToBank({amount:50,receiptId:'next-pay',currency:'japan',roleId:'cook',slotId:'kitchen',day}).ok);
assert(ledger.refund('npc-meal').ok);
assert.deepEqual([ledger.balances().japan.cash,ledger.balances().japan.bank],[40,260]);
assert.equal(ledger.state().interest.minimum.japan,160);
ledger=createCurrencyLedger({...options,saved:durable});assert.equal(ledger.loadError,null);assert(ledger.refund('npc-meal').replayed);
day=2;assert(ledger.observeDay().ok);assert.equal(ledger.balances().japan.bank,261,'Only the actual lowest 160 bank earns 1');
assert.equal(ledger.reserveFromTotal(302,'too-much','japan').code,'insufficient-funds');
assert(ledger.reserveFromTotal(301,'all-funds','japan').ok);assert(ledger.settle('all-funds').ok);
assert.equal(ledger.refund('all-funds').code,'reservation-settled');
assert.equal(ledger.balances().japan.bank,0);
assert.equal(ledger.balances().japan.cash,0);
console.log('PASS NPC cash-first total, exact original-source refund, player cash-only, failed save/replay and daily bank minimum');
