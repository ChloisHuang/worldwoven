import assert from 'node:assert/strict';
import {createJapanServiceOrders,JAPAN_SERVICE_POINTS as P} from '../source/game/japan-service-orders.js';
import {createJapanPlayerService} from '../source/game/japan-player-service.js';
import {createFacilityQueue} from '../source/game/npc-facilities.js';
const facilities=createFacilityQueue(),board=createJapanServiceOrders(),desk='japan-service-reception';
const bench={id:'rest-seat',kind:'seat',center:[0,3.8,7.55],anchor:[0,3.8,7.4]};
const player={root:{position:{x:P.playerReception[0],y:P.playerReception[1],z:P.playerReception[2]},userData:{appearance:{bodyPreset:'masculine-lean',wardrobePreset:'haori-trouser'}}}};
const service=createJapanPlayerService({board,furniture:{items:[bench],facilities,releaseActor:id=>facilities.releaseActor(id)},getPlayer:()=>player});
assert(facilities.request(desk,'busy-guest'));
assert(service.register('cloud-leaf').ok);
const id=service.state().visit.id;
assert.equal(service.state().visit.stage,'arriving');
assert(facilities.state().find(f=>f.id===desk).queue.includes(id));
player.root.position.z=35;service.update(1/30);
assert.equal(service.state().visit?.id??null,null,'Walking away from queued registration cancels the unissued ticket');
assert(!facilities.state().find(f=>f.id===desk).queue.includes(id),'Absent customer must not remain at the queue head');
facilities.release(desk,'busy-guest');
assert(facilities.request(desk,'next-guest'),'Next real visitor can use the counter');
board.dispose();facilities.dispose();
console.log('PASS: queued player departure releases reception for the next visitor');
